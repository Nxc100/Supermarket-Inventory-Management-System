import { test, expect } from '../../frontend/test-support/playwright'
test('operational stock traces batches and movements while foreign purchase stays plain text', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('textbox', { name: '*用户名', exact: true }).fill('buyer02')
  await page.getByRole('textbox', { name: '*密码', exact: true }).fill('Test123456')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: /欢迎回来/ })).toBeVisible()
  await page.getByRole('menuitem', { name: '库存查询', exact: true }).click()
  await page.getByRole('textbox', { name: '库存关键词', exact: true }).fill('P0007')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  const row=page.getByRole('row').filter({hasText:'P0007'})
  await expect(row).toContainText('40 件')
  await row.getByRole('link', {name:'批次详情',exact:true}).click()
  await page.getByRole('textbox', {name:'批次关键词',exact:true}).fill('CG-DEMO-0001')
  await page.getByRole('button', {name:'查询批次',exact:true}).click()
  const batch=page.getByRole('row').filter({hasText:'CG-DEMO-0001'})
  await expect(batch).toContainText('8.00')
  await expect(batch).toContainText('2026-09-01 00:00:00')
  await expect(batch).toContainText('仅追溯单号')
  await expect(batch.getByRole('link',{name:'CG-DEMO-0001',exact:true})).toHaveCount(0)
  await batch.getByRole('link',{name:'批次流水',exact:true}).click()
  await expect(page.getByRole('heading',{name:'库存流水',exact:true})).toBeVisible()
  await expect(page.getByRole('row').filter({hasText:'采购入库'})).toContainText('+40')
  await expect(page.getByRole('row').filter({hasText:'销售出库'}).first()).toContainText('-')
  await expect(page.getByRole('button',{name:'直接修改库存',exact:true})).toHaveCount(0)
})
