import { test, expect } from '../../frontend/test-support/playwright'
import { login, confirm, stockedProduct } from './support/fixtures'

test('lost purchase and stocktake responses retain input, block another write and lead to persisted result checks', async ({ page }) => {
  test.setTimeout(150000)
  const product = await stockedProduct(page)
  await login(page, 'buyer01')
  await page.getByRole('menuitem', { name: '采购单管理', exact: true }).click()
  await page.getByRole('button', { name: '新建采购', exact: true }).click()
  await page.getByRole('button', { name: '选择供应商', exact: true }).click()
  const suppliers = page.getByRole('dialog', { name: '选择启用供应商', exact: true })
  await suppliers.getByRole('textbox', { name: '供应商关键词', exact: true }).fill('本地综合供应商')
  await suppliers.getByRole('button', { name: '搜索供应商', exact: true }).click()
  await suppliers.getByRole('row').filter({ hasText: 'SUP001' }).getByRole('button', { name: '选择供应商', exact: true }).click()
  await page.getByRole('button', { name: '添加商品', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '添加采购商品', exact: true })
  await picker.getByRole('textbox', { name: '选品关键词', exact: true }).fill(product.code)
  await picker.getByRole('button', { name: '搜索商品', exact: true }).click()
  await picker.getByRole('button', { name: '添加此商品', exact: true }).click()
  await page.getByRole('spinbutton', { name: '第1行采购数量', exact: true }).fill('2')
  let purchasePosts = 0
  await page.route('**/api/v1/purchases', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    purchasePosts++
    const result = await route.fetch()
    expect(result.status()).toBe(200)
    await route.abort('failed')
  })
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '本次采购保存结果待核实' })).toBeVisible()
  await expect(page.getByRole('spinbutton', { name: '第1行采购数量', exact: true })).toHaveValue('2')
  await expect(page.getByRole('button', { name: '保存草稿', exact: true })).toBeDisabled()
  await page.unroute('**/api/v1/purchases')
  await page.getByRole('button', { name: '去核实采购保存结果', exact: true }).click()
  await confirm(page, '确认离开')
  await expect(page.getByRole('textbox', { name: '采购查询关键词', exact: true })).toHaveValue('本地综合供应商')
  await page.getByRole('link', { name: '查看详情', exact: true }).first().click()
  await expect(page.getByRole('row').filter({ hasText: product.code })).toContainText('2')
  const purchaseUrl = page.url()
  expect(purchasePosts).toBe(1)

  await page.getByRole('menuitem', { name: '库存盘点', exact: true }).click()
  await page.getByRole('button', { name: '新建盘点', exact: true }).click()
  await page.getByRole('textbox', { name: '盘点选品关键词', exact: true }).fill(product.code)
  await page.getByRole('button', { name: '搜索盘点商品', exact: true }).click()
  await page.getByRole('row').filter({ hasText: product.code }).getByRole('button', { name: '选取商品', exact: true }).click()
  let stocktakePosts = 0
  await page.route('**/api/v1/stocktakes', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    stocktakePosts++
    const result = await route.fetch()
    expect(result.status()).toBe(200)
    await route.abort('failed')
  })
  await page.getByRole('button', { name: '开始盘点', exact: true }).click()
  await confirm(page, '开始盘点')
  await expect(page.getByRole('alert').filter({ hasText: '本次盘点发起结果待核实' })).toBeVisible()
  await expect(page.getByRole('button', { name: '开始盘点', exact: true })).toBeDisabled()
  await expect(page.getByRole('heading', { name: '本次范围 · 1 种', exact: true })).toBeVisible()
  await page.unroute('**/api/v1/stocktakes')
  await page.getByRole('button', { name: '去列表核实盘点结果', exact: true }).click()
  await confirm(page, '确认离开')
  await expect(page.getByRole('textbox', { name: '盘点关键词', exact: true })).toHaveValue(product.code)
  await expect(page.locator('main .el-table__body-wrapper tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: '查看盘点', exact: true }).click()
  expect(stocktakePosts).toBe(1)
  await page.getByRole('button', { name: '关闭盘点', exact: true }).click()
  const close = page.getByRole('dialog', { name: '关闭盘点', exact: true })
  await close.getByRole('textbox').fill('响应恢复验证结束，关闭本次盘点释放冻结，保留库存')
  await close.getByRole('button', { name: '关闭盘点', exact: true }).click()
  await expect(close).toBeHidden()
  await expect(page.getByText('已关闭', { exact: true }).first()).toBeVisible()
  await page.goto(purchaseUrl)
  await page.getByRole('button', { name: '关闭采购', exact: true }).click()
  const closePurchase = page.getByRole('dialog', { name: '关闭采购', exact: true })
  await closePurchase.getByRole('textbox').fill('恢复已提交草稿后关闭专属验证单，不改变库存')
  await closePurchase.getByRole('button', { name: '关闭采购', exact: true }).click()
  await expect(closePurchase).toBeHidden()
})
