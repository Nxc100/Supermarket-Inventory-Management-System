import { test, expect, type Page } from '../../frontend/test-support/playwright'

async function login(page: Page, name: string) {
  await page.goto('/login')
  await page.getByRole('textbox', { name: '*用户名', exact: true }).fill(name)
  await page.getByRole('textbox', { name: '*密码', exact: true }).fill('Test123456')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: /欢迎回来/ })).toBeVisible()
}
async function logout(page: Page) {
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page).toHaveURL(/\/login/)
}
async function confirm(page: Page, label: string, reason?: string) {
  const dialog = page.getByRole('dialog').filter({ has: page.getByRole('button', { name: label, exact: true }) })
  if (reason) await dialog.getByRole('textbox').fill(reason)
  await dialog.getByRole('button', { name: label, exact: true }).click()
}
